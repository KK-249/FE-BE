	SUBROUTINE SOLOUT
C
C  IDENTIFY THE SOLUTION VECTOR
C
        COMMON /BG/BIG
	COMMON /CONTR/NNODE,NELEM
	COMMON /ELEM/NODE(8,4000)
	COMMON /MATRX/A(4040,4000),B(4040),XS(4000)
	COMMON /SOL/SP(4000),VN(8,4000)
	COMMON /BCC/CA(8,4000),CB(8,4000),CC(8,4000)
        COMPLEX BIG,A,B,XS,SP,VN,CA,CB,CC
C
	DO 100 I=1,NNODE
	  IF(SP(I).EQ.BIG) SP(I)=XS(I)
100	CONTINUE
C
	DO 300 K=1,NELEM
          I34=8
          IF(NODE(3,K).EQ.NODE(4,K)) I34=3
	  DO 200 J=1,I34
	    IF(VN(J,K).NE.BIG) GO TO 200
            NOD=NODE(J,K)
	    IF(CB(J,K).EQ.0.0) THEN
	      VN(J,K)=XS(NOD)
	    ELSE
	      VN(J,K)=(CC(J,K)-CA(J,K)*SP(NOD))/CB(J,K)
            END IF
200       CONTINUE
300     CONTINUE
C
C    PRINT OUT BOUNDARY SOLUTION
C
      
C

600     CONTINUE
        RETURN
        END