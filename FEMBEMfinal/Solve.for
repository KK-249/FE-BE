      SUBROUTINE SOLVE
      COMMON /CONTR/NNODE,NELEM
      COMMON /MATRX/A(4040,4000),B(4040),XS(4000)
      COMMON /SOLVER/AUX(4000),AUX2(4040),IPVT(4000)
      COMMON /CHI/NCH,XCH(20),YCH(20)

      COMPLEX A,B,XS,AUX,AUX2

      NR=NNODE+NCH
      NC=NNODE

      CALL SOLCHI(A,NR,NC,B,AUX,AUX2,IPVT,XS,4040,4000)

      RETURN
      END